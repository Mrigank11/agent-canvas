// Regenerates server/vendor/*: the plugin server is bundled by Paseo with esbuild and runs with no node_modules,
// so resvg (pure JS glue + wasm) and the font are embedded as TypeScript modules instead of installed.
//   node scripts/vendor-resvg.mjs   (needs network for `npm pack`, and the two Liberation fonts installed)
// @resvg/resvg-wasm is MPL-2.0, Liberation Sans is SIL OFL 1.1.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { tmpdir } from "node:os";
import { join } from "node:path";

const out = new URL("../server/vendor/", import.meta.url).pathname;
const tmp = mkdtempSync(join(tmpdir(), "resvg-"));
execFileSync("npm", ["pack", "@resvg/resvg-wasm@2.6.2", "--silent"], { cwd: tmp });
execFileSync("tar", ["xzf", "resvg-resvg-wasm-2.6.2.tgz"], { cwd: tmp });
const pkg = (f) => readFileSync(join(tmp, "package", f));
const b64gz = (buf) => gzipSync(buf, { level: 9 }).toString("base64");

writeFileSync(join(out, "resvg-wasm.ts"), `// @ts-nocheck\n// Vendored @resvg/resvg-wasm 2.6.2 (MPL-2.0), unmodified glue. Regenerate with scripts/vendor-resvg.mjs.\n${pkg("index.mjs").toString("utf8")}`);
writeFileSync(join(out, "resvg-wasm-bin.ts"), `// Generated by scripts/vendor-resvg.mjs: resvg_wasm_bg.wasm, gzipped, base64.\nexport const RESVG_WASM_GZ_B64 = "${b64gz(pkg("index_bg.wasm"))}";\n`);
const font = (f) => readFileSync(`/usr/share/fonts/liberation/${f}`);
writeFileSync(join(out, "fonts.ts"), `// Generated by scripts/vendor-resvg.mjs: Liberation Sans Regular and Bold (SIL OFL 1.1), gzipped, base64.\nexport const FONT_FAMILY = "Liberation Sans";\nexport const FONTS_GZ_B64 = [\n  "${b64gz(font("LiberationSans-Regular.ttf"))}",\n  "${b64gz(font("LiberationSans-Bold.ttf"))}",\n];\n`);
