// Regenerates server/vendor/graphviz-worker.ts and vega-bundle.ts: the plugin server is bundled by Paseo with esbuild and
// runs with no node_modules, so Graphviz-wasm (with its worker glue) and vega + vega-lite are embedded as gzipped base64.
//   node scripts/vendor-render.mjs   (needs network for npm; installs esbuild/vega into a temp dir, one bundle at a time)
// @hpcc-js/wasm-graphviz is Apache-2.0, Graphviz EPL-1.0, vega / vega-lite / vega-interpreter BSD-3-Clause.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { tmpdir } from "node:os";
import { join } from "node:path";

const out = new URL("../server/vendor/", import.meta.url).pathname;
const tmp = mkdtempSync(join(tmpdir(), "render-"));
const run = (cmd, args, cwd = tmp) => execFileSync(cmd, args, { cwd, stdio: ["ignore", "inherit", "inherit"] });
const b64gz = (s) => gzipSync(Buffer.from(s), { level: 9 }).toString("base64");

run("npm", ["init", "-y", "--silent"]);
run("npm", ["i", "--silent", "--no-audit", "--no-fund", "@hpcc-js/wasm-graphviz@1.30.0", "vega@6.4.0", "vega-lite@6.5.0", "vega-interpreter@2.3.2", "esbuild@0.28.2"]);

// 1. Graphviz: the package's single-file ESM (wasm inlined) + a message loop, run as a data: URL worker.
let gv = readFileSync(join(tmp, "node_modules/@hpcc-js/wasm-graphviz/dist/index.js"), "utf8").replace(/\n\/\/# sourceMappingURL.*$/, "");
gv = gv.replace(/export\s*\{[^}]*\};?\s*$/, "");
const glue = `
import { parentPort } from "node:worker_threads";
const ready = Ve.load();   // Ve: the minified name of the package's Graphviz class
ready.then(() => parentPort.postMessage({ ready: true }), (e) => parentPort.postMessage({ ready: false, error: String(e && e.message || e) }));
parentPort.on("message", async ({ id, dot }) => {
  try { const g = await ready; parentPort.postMessage({ id, svg: g.dot(dot, "svg") }); }
  catch (e) { parentPort.postMessage({ id, error: String((e && e.message) || e) }); }
});
`;
// the glue imports must precede nothing else in an ES module, but imports are hoisted so appending is fine
writeFileSync(join(out, "graphviz-worker.ts"), `// Generated by scripts/vendor-render.mjs: @hpcc-js/wasm-graphviz 1.30.0 (Apache-2.0; Graphviz EPL-1.0) + worker loop, ES module source, gzipped, base64.\nexport const GRAPHVIZ_WORKER_GZ_B64 = "${b64gz(gv + glue)}";\n`);

// 2. Vega-Lite compile + Vega dataflow/SVG + the AST interpreter (so no Function/eval runs agent expressions).
writeFileSync(join(tmp, "entry.js"), `import { compile } from "vega-lite";\nimport { parse, View } from "vega";\nimport { expressionInterpreter } from "vega-interpreter";\nexport { compile, parse, View, expressionInterpreter };\n`);
run("npx", ["esbuild", "entry.js", "--bundle", "--format=esm", "--platform=neutral", "--main-fields=module,main", "--conditions=import,module,browser", "--minify", "--outfile=vega.mjs", "--log-level=warning", "--legal-comments=none"]);
writeFileSync(join(out, "vega-bundle.ts"), `// Generated by scripts/vendor-render.mjs: vega 6.4.0 + vega-lite 6.5.0 + vega-interpreter 2.3.2 (BSD-3-Clause), one minified ES module, gzipped, base64.\nexport const VEGA_GZ_B64 = "${b64gz(readFileSync(join(tmp, "vega.mjs"), "utf8"))}";\n`);
